CREATE TABLE country (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,       -- краткое название
    fullname VARCHAR(200) NOT NULL,   -- полное название
    region VARCHAR(40) NOT NULL,
    CONSTRAINT country_region_check CHECK (region IN (
        'Азия', 'Европа', 'Африка', 'Австралия и Океания',
        'Северная Америка', 'Южная и Латинская Америка'
    ))
);

CREATE TABLE club (
    club_id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,       -- краткое название
    fullname VARCHAR(200) NOT NULL    -- полное название
);

CREATE TABLE team (
    team_id SERIAL PRIMARY KEY,
    team_name VARCHAR(100) NOT NULL,
    country_id INTEGER REFERENCES country(id),
    club_id INTEGER REFERENCES club(club_id),
    -- Команда связана либо со страной, либо с клубом: строго одна ссылка.
    CONSTRAINT team_origin_check CHECK (
        (country_id IS NOT NULL AND club_id IS NULL)
        OR (country_id IS NULL AND club_id IS NOT NULL)
    )
);

CREATE TABLE player (
    id SERIAL PRIMARY KEY,
    lastname VARCHAR(100) NOT NULL,
    name VARCHAR(100) NOT NULL,
    birthdate DATE NOT NULL,
    country_id INTEGER NOT NULL REFERENCES country(id),
    team_id INTEGER NOT NULL REFERENCES team(team_id),
    number INTEGER NOT NULL,
    amplua VARCHAR(30) NOT NULL,
    -- Для учебной модели считаем дублем совпадение фамилии, имени и даты рождения. Тезки с разными датами рождения допускаются.
    CONSTRAINT player_name_birthdate_unique UNIQUE (lastname, name, birthdate),
    -- Номер уникален внутри команды, но может повторяться в другой команде.
    CONSTRAINT player_team_number_unique UNIQUE (team_id, number),
    CONSTRAINT player_number_check CHECK (number > 0),
    CONSTRAINT player_amplua_check CHECK (amplua IN (
        'Вратарь', 'Защитник', 'Полузащитник', 'Нападающий'
    ))
);

CREATE TABLE games (
    id SERIAL PRIMARY KEY,
    first_team INTEGER NOT NULL REFERENCES team(team_id),
    second_team INTEGER NOT NULL REFERENCES team(team_id),
    day DATE NOT NULL,
    time TIME NOT NULL,
    address VARCHAR(250) NOT NULL,
    game_level VARCHAR(30) NOT NULL,
    subgroup VARCHAR(50),
    CONSTRAINT games_different_teams_check CHECK (first_team <> second_team),
    CONSTRAINT games_level_check CHECK (game_level IN (
        'Групповой раунд', '1/8 финала', '1/4 финала',
        'Полуфинал', 'Финал', 'Игра за 3-е место'
    )),
    -- Название подгруппы обязательно только для группового раунда.
    CONSTRAINT games_subgroup_check CHECK (
        (game_level = 'Групповой раунд' AND subgroup IS NOT NULL AND TRIM(subgroup) <> '')
        OR (game_level <> 'Групповой раунд' AND subgroup IS NULL)
    )
);

CREATE TABLE result (
    game_id INTEGER PRIMARY KEY REFERENCES games(id),
    first_team_scores INTEGER NOT NULL,
    second_team_scores INTEGER NOT NULL,
    -- По умолчанию счет послематчевой серии пенальти отсутствует.
    -- Если серия пенальти проводилась, оба значения указываются явно.
    -- NULL означает отсутствие серии, 0 — ни одного реализованного удара.
    first_team_penalty_scores INTEGER,
    second_team_penalty_scores INTEGER,
    first_team_points INTEGER,
    second_team_points INTEGER,
    -- Количество голов неотрицательно.
    CONSTRAINT result_scores_check CHECK (
        first_team_scores >= 0 AND second_team_scores >= 0
    ),
    -- Счет серии пенальти неотрицателен.
    CONSTRAINT result_penalty_scores_check CHECK (
        first_team_penalty_scores >= 0 AND second_team_penalty_scores >= 0
    ),
    -- Счет серии пенальти либо отсутствует у обеих команд, либо заполнен у обеих при равном игровом счете.
    -- Завершенная серия пенальти должна определять победителя.
    CONSTRAINT result_penalty_pair_check CHECK (
        (first_team_penalty_scores IS NULL AND second_team_penalty_scores IS NULL)
        OR (
            first_team_penalty_scores IS NOT NULL AND second_team_penalty_scores IS NOT NULL
            AND first_team_scores = second_team_scores
            AND first_team_penalty_scores <> second_team_penalty_scores
        )
    ),
    -- Очки либо отсутствуют у обеих команд, либо заполнены у обеих по системе 3 - победа /1 - ничья /0 - поражение по счету.
    -- Очки учитываются только для группового этапа, где серия пенальти не предусмотрена. 
    -- В плей-офф, включая победу по пенальти, оба поля очков остаются NULL.
    CONSTRAINT result_points_check CHECK (
        (first_team_points IS NULL AND second_team_points IS NULL)
        OR (
            first_team_points IS NOT NULL AND second_team_points IS NOT NULL
            AND first_team_penalty_scores IS NULL AND second_team_penalty_scores IS NULL
            AND (
                (first_team_scores > second_team_scores AND first_team_points = 3 AND second_team_points = 0)
                OR (first_team_scores < second_team_scores AND first_team_points = 0 AND second_team_points = 3)
                OR (first_team_scores = second_team_scores AND first_team_points = 1 AND second_team_points = 1)
            )
        )
    )
);

CREATE TABLE goals (
    id SERIAL PRIMARY KEY,
    game_id INTEGER NOT NULL REFERENCES games(id),
    player_id INTEGER NOT NULL REFERENCES player(id),
    minute INTEGER NOT NULL,
    CONSTRAINT goals_minute_check CHECK (minute BETWEEN 1 AND 120)
);
-- Указываем минуту матча без секунд. Компенсированное время первого и второго таймов записываем как 45 и 90 минут соответственно для простоты реализации.
-- Дополнительные таймы учитываем до 120-й минуты; их компенсированное время записываем как 105 и 120 соответственно.

CREATE TABLE penalty (
    id SERIAL PRIMARY KEY,
    game_id INTEGER NOT NULL REFERENCES games(id),
    player_id INTEGER NOT NULL REFERENCES player(id),
    minute INTEGER NOT NULL,
    color_card CHAR(1) NOT NULL,
    why VARCHAR(500),  -- необязательное обоснование карточки (какое было нарушение по правилам)
    CONSTRAINT penalty_minute_check CHECK (minute BETWEEN 1 AND 120),
    CONSTRAINT penalty_color_check CHECK (color_card IN ('ж', 'к'))
);
-- Время указываем в целых минутах без секунд; компенсированное время записываем по тем же правилам, что и в goals.

